// Builds the app icon files from the source icon.png in the repo root (256x256 PNG with alpha):
// build/icon.png, build/icon.ico and src/electron/iconData.ts. Pure Node, no dependencies.
// Run with: npm run icon
/* global console, process, Buffer */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const png = readFileSync('icon.png');
const isPng = png
  .subarray(0, 8)
  .equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]));
if (!isPng || png.readUInt32BE(16) !== 256 || png.readUInt32BE(20) !== 256) {
  console.error('icon.png in the repo root must be a 256x256 PNG.');
  process.exit(1);
}

// ICO container holding the 256x256 PNG (width/height 0 means 256).
const ico = Buffer.alloc(22);
ico.writeUInt16LE(0, 0);
ico.writeUInt16LE(1, 2);
ico.writeUInt16LE(1, 4);
ico[6] = 0;
ico[7] = 0;
ico.writeUInt16LE(1, 10);
ico.writeUInt16LE(32, 12);
ico.writeUInt32LE(png.length, 14);
ico.writeUInt32LE(22, 18);

mkdirSync('build', { recursive: true });
writeFileSync('build/icon.png', png);
writeFileSync('build/icon.ico', Buffer.concat([ico, png]));
writeFileSync(
  'src/electron/iconData.ts',
  `// Generated by scripts/make-icon.mjs - do not edit.\nexport const ICON_PNG_BASE64 =\n  '${png.toString('base64')}';\n`,
);
console.log(`icon.png ${png.length} bytes`);
