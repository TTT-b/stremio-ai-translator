// Generates the app icon (build/icon.png, build/icon.ico) and src/electron/iconData.ts.
// Pure Node, no dependencies. Run with: node scripts/make-icon.mjs
/* global console, Buffer */
import { deflateSync } from 'node:zlib';
import { mkdirSync, writeFileSync } from 'node:fs';

const N = 256;
const SS = 4; // supersampling per axis

const lerp = (a, b, t) => a + (b - a) * t;
const inRoundedSquare = (x, y) => {
  const r = 58;
  const dx = Math.max(Math.abs(x - N / 2) - (N / 2 - r), 0);
  const dy = Math.max(Math.abs(y - N / 2) - (N / 2 - r), 0);
  return dx * dx + dy * dy <= r * r;
};
const sign = (px, py, ax, ay, bx, by) => (px - bx) * (ay - by) - (ax - bx) * (py - by);
const inTriangle = (x, y, [a, b, c]) => {
  const d1 = sign(x, y, ...a, ...b);
  const d2 = sign(x, y, ...b, ...c);
  const d3 = sign(x, y, ...c, ...a);
  return !((d1 < 0 || d2 < 0 || d3 < 0) && (d1 > 0 || d2 > 0 || d3 > 0));
};
const PLAY = [
  [98, 74],
  [98, 182],
  [190, 128],
];
const inSparkle = (x, y) => {
  const cx = 70;
  const cy = 70;
  const r = 30;
  return Math.sqrt(Math.abs(x - cx)) + Math.sqrt(Math.abs(y - cy)) <= Math.sqrt(r);
};

const raw = Buffer.alloc((N * 4 + 1) * N);
for (let y = 0; y < N; y++) {
  raw[y * (N * 4 + 1)] = 0;
  for (let x = 0; x < N; x++) {
    let r = 0;
    let g = 0;
    let b = 0;
    let a = 0;
    for (let sy = 0; sy < SS; sy++) {
      for (let sx = 0; sx < SS; sx++) {
        const px = x + (sx + 0.5) / SS;
        const py = y + (sy + 0.5) / SS;
        if (!inRoundedSquare(px, py)) continue;
        const t = (px + py) / (2 * N);
        let c = [lerp(0x63, 0xd9, t), lerp(0x66, 0x46, t), lerp(0xf1, 0xef, t)];
        if (inTriangle(px, py, PLAY) || inSparkle(px, py)) c = [255, 255, 255];
        r += c[0];
        g += c[1];
        b += c[2];
        a += 1;
      }
    }
    const o = y * (N * 4 + 1) + 1 + x * 4;
    if (a > 0) {
      raw[o] = Math.round(r / a);
      raw[o + 1] = Math.round(g / a);
      raw[o + 2] = Math.round(b / a);
      raw[o + 3] = Math.round((a / (SS * SS)) * 255);
    }
  }
}

const crcTable = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
const crc = (buf) => {
  let c = 0xffffffff;
  for (const byte of buf) c = crcTable[(c ^ byte) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
};
const chunk = (type, data) => {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type), data]);
  const sum = Buffer.alloc(4);
  sum.writeUInt32BE(crc(body));
  return Buffer.concat([len, body, sum]);
};
const ihdr = Buffer.alloc(13);
ihdr.writeUInt32BE(N, 0);
ihdr.writeUInt32BE(N, 4);
ihdr[8] = 8; // bit depth
ihdr[9] = 6; // RGBA
const png = Buffer.concat([
  Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
  chunk('IHDR', ihdr),
  chunk('IDAT', deflateSync(raw, { level: 9 })),
  chunk('IEND', Buffer.alloc(0)),
]);

// ICO container holding the 256x256 PNG (width/height 0 means 256).
const ico = Buffer.alloc(22);
ico.writeUInt16LE(0, 0);
ico.writeUInt16LE(1, 2);
ico.writeUInt16LE(1, 4);
ico[6] = 0;
ico[7] = 0;
ico.writeUInt16LE(1, 10);
ico.writeUInt16LE(32, 12);
ico.writeUInt32LE(png.length, 14);
ico.writeUInt32LE(22, 18);

mkdirSync('build', { recursive: true });
writeFileSync('build/icon.png', png);
writeFileSync('build/icon.ico', Buffer.concat([ico, png]));
writeFileSync(
  'src/electron/iconData.ts',
  `// Generated by scripts/make-icon.mjs - do not edit.\nexport const ICON_PNG_BASE64 =\n  '${png.toString('base64')}';\n`,
);
console.log(`icon.png ${png.length} bytes`);
